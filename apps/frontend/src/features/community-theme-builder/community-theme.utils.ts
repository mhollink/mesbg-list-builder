import type { BrandColorTokens } from "~/theme/theme.types.ts";

export const BRAND_ROLES = [
  "primary",
  "secondary",
  "tertiary",
  "accent",
  "highlight",
] as const satisfies readonly (keyof BrandColorTokens)[];

export const BRAND_DESCRIPTIONS: Record<keyof BrandColorTokens, string> = {
  primary: "Main actions, links and active controls",
  secondary: "Supporting actions and warband structure",
  tertiary: "Sections, categories and organizational details",
  accent: "Special profiles, rules and heroic details",
  highlight: "Selected equipment and contextual emphasis",
};

export interface CommunityThemeDraft {
  name: string;
  author: string;
  description: string;
  colors: BrandColorTokens;
}

export function isHexColor(value: string): boolean {
  return /^#[0-9a-fA-F]{6}$/.test(value);
}

export function getThemeSlug(name: string): string {
  const slug = name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48)
    .replace(/-$/, "");

  return `community-${slug || "theme"}`;
}

export function isValidCommunityTheme(draft: CommunityThemeDraft): boolean {
  return (
    draft.name.trim().length > 0 &&
    draft.name.trim().length <= 60 &&
    draft.author.trim().length > 0 &&
    draft.author.trim().length <= 60 &&
    draft.description.length <= 160 &&
    BRAND_ROLES.every((role) => isHexColor(draft.colors[role]))
  );
}

export function generateThemeSource(draft: CommunityThemeDraft): string {
  if (!isValidCommunityTheme(draft)) {
    throw new Error("Theme details and colors must be valid before export.");
  }

  const id = getThemeSlug(draft.name);
  const declaration = `${id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Theme`;
  const text = (value: string) => JSON.stringify(value.trim());
  const colors = BRAND_ROLES.map(
    (role) =>
      `    ${role}: ${JSON.stringify(draft.colors[role].toUpperCase())},`,
  ).join("\n");

  return `// Generated by Community Theme Builder.
// To register: add ${JSON.stringify(id)} to ThemePresetId in theme.types.ts,
// then import and register ${declaration} in themePresets.ts.
import { createThemeTokens } from "../../createThemeTokens.ts";
import type { ThemePreset } from "../../theme.types.ts";

export const ${declaration}: ThemePreset = {
  id: ${JSON.stringify(id)},
  name: ${text(draft.name)},
  description: ${text(draft.description)},
  category: "patreon",
  creator: {
    name: ${text(draft.author)},
  },
  colors: createThemeTokens({
${colors}
  }),
};
`;
}
